/**
 * Pharos demo AI endpoint, running on Cloudflare Workers AI (free daily allowance).
 *
 *   GET  /health   → is it up, which model, how many AI answers are left today
 *   POST /chat     → { input }  the Keeper answers from the help-center excerpts in `input`
 *   POST /triage   → { input }  returns the triage JSON for the ticket in `input`
 *
 * Protections, so the free allowance can't be drained:
 *   - Only the origins in ALLOWED_ORIGINS get answers (your GitHub Pages site).
 *   - The system prompts live HERE, not in the page, so callers can't repurpose the model.
 *   - Input size is capped, output length is capped.
 *   - A per-visitor and a global daily cap, counted in a KV namespace bound as LIMITS.
 *     Visitor IPs are hashed before they're used as a key; raw IPs are never stored.
 *
 * Bindings (Settings > Bindings in the Cloudflare dashboard):
 *   AI      Workers AI
 *   LIMITS  a KV namespace
 * Variables (Settings > Variables and secrets):
 *   ALLOWED_ORIGINS     e.g. https://scenebiscuit-cell.github.io
 *   PER_VISITOR_DAILY   default 10
 *   GLOBAL_DAILY        default 40 (keeps you well under the free allowance)
 *   MODEL               optional; a different Workers AI text model id
 *
 * This file is generated by build_demo.py from worker/worker.template.js. Edit the template, not this file.
 */
const DEFAULT_MODEL = "@cf/meta/llama-3.3-70b-instruct-fp8-fast";
const PROMPTS = /*__PROMPTS__*/null;
const LIMITS = { chat: { maxInput: /*__CHAT_MAX_INPUT__*/8000, maxTokens: 400 }, triage: { maxInput: 14000, maxTokens: 900 } };

export default {
  async fetch(req, env, ctx) {
    const allowed = String(env.ALLOWED_ORIGINS || "").split(",").map(s => s.trim().replace(/\/$/, "")).filter(Boolean);
    const origin = req.headers.get("Origin") || "";
    const okOrigin = allowed.includes(origin);
    const cors = {
      "Access-Control-Allow-Origin": okOrigin ? origin : (allowed[0] || "null"),
      "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type",
      "Access-Control-Max-Age": "86400",
      "Vary": "Origin",
    };
    const json = (obj, status = 200) => new Response(JSON.stringify(obj), { status, headers: { ...cors, "Content-Type": "application/json" } });

    if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
    const path = new URL(req.url).pathname.replace(/\/$/, "") || "/";
    const perVisitor = Number(env.PER_VISITOR_DAILY) || 10;
    const global = Number(env.GLOBAL_DAILY) || 40;
    const day = new Date().toISOString().slice(0, 10);
    const MODEL = env.MODEL || DEFAULT_MODEL;

    if (path === "/health" || path === "/") {
      if (!env.AI || !env.LIMITS) return json({ ok: false, error: "not_configured", message: "Add the AI and LIMITS bindings in the Worker's settings." }, 503);
      const used = await count(env, `all:${day}`);
      return json({ ok: true, model: MODEL, remaining_today: Math.max(0, global - used), per_visitor_daily: perVisitor });
    }
    if (req.method !== "POST" || !(path === "/chat" || path === "/triage")) return json({ error: "not_found" }, 404);
    if (!okOrigin) return json({ error: "forbidden_origin", message: "This AI endpoint only serves the Pharos demo site." }, 403);
    if (!env.AI || !env.LIMITS) return json({ error: "not_configured", message: "The demo's AI isn't set up yet." }, 503);

    const kind = path.slice(1);
    let body;
    try { body = await req.json(); } catch { return json({ error: "bad_request", message: "Send JSON with an `input` field." }, 400); }
    const input = typeof body?.input === "string" ? body.input.trim() : "";
    if (!input) return json({ error: "bad_request", message: "Missing input." }, 400);
    if (input.length > LIMITS[kind].maxInput) return json({ error: "too_long", message: "That request is too long for the demo." }, 413);

    // Daily caps. KV is eventually consistent, so these are approximate, which is fine for a demo.
    const visitor = await sha256((req.headers.get("CF-Connecting-IP") || "unknown") + "|" + day);
    const vKey = `v:${day}:${visitor.slice(0, 24)}`, gKey = `all:${day}`;
    const [vUsed, gUsed] = await Promise.all([count(env, vKey), count(env, gKey)]);
    if (gUsed >= global) return json({ error: "daily_limit", message: "The demo has used today's free AI answers. It resets at midnight UTC." }, 429);
    if (vUsed >= perVisitor) return json({ error: "visitor_limit", message: `You've used your ${perVisitor} AI answers for today. The docs-only mode still works.` }, 429);
    ctx.waitUntil(Promise.all([bump(env, vKey, vUsed), bump(env, gKey, gUsed)]));

    try {
      const out = await env.AI.run(MODEL, {
        messages: [{ role: "system", content: PROMPTS[kind] }, { role: "user", content: input }],
        max_tokens: LIMITS[kind].maxTokens,
        temperature: 0.2,
      });
      const r = out?.response;
      const raw = typeof r === "string" ? r : r ? JSON.stringify(r) : "";
      const text = kind === "triage" ? polishTriage(raw, input) : scrub(raw);
      return json({ text, model: MODEL, remaining_today: Math.max(0, global - gUsed - 1) });
    } catch (e) {
      return json({ error: "model_error", message: "The AI model didn't answer. Try again in a moment." }, 502);
    }
  },
};

// ---------- voice guard ----------
// Smaller open models don't always follow the house style, so the Worker enforces the
// non-negotiables after the model answers: no corporate filler, the standard opening,
// and the standard sign-off. The agent still reviews every draft before it's sent.
const BANNED = [
  /\bI (?:completely |totally |truly )?understand (?:your|how) (?:frustrat\w*|frustrating[^.!?]*)/i,
  /\bI understand (?:your|the) (?:concern|frustration)/i,
  /\bwe apologi[sz]e for any inconvenience/i,
  /\bsorry for any inconvenience/i,
  /\brest assured\b/i,
  /\bplease be advised\b/i,
  /\bI hope this (?:e-?mail|message) finds you well/i,
  /\bthank(?:s| you) for reaching out\b/i,
];
const OPENING = "Thank you for contacting Pharos.";
const AGENT = "Alex";

// Drop any sentence that contains a banned phrase.
function scrub(text) {
  return String(text)
    .split(/\n/)
    .map(line => line.split(/(?<=[.!?])\s+/).filter(s => !BANNED.some(re => re.test(s))).join(" "))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function fixDraft(draft, firstName = "") {
  // Greeting: pull "Hi Name," off first so scrubbing a filler sentence can't take it with it.
  let greeting = "", body = String(draft).trim();
  const m = body.match(/^((?:hi|hello|hey|dear)\b[^,\n]{0,40},)\s*/i);
  if (m) { greeting = m[1]; body = body.slice(m[0].length); }
  let rest = scrub(body);
  if (!rest && !greeting) return rest;
  // The model sometimes skips the greeting; the ticket's From: line has the name.
  if (!greeting && firstName) greeting = `Hi ${firstName},`;
  // Opening line.
  if (!/^thank you for contacting pharos/i.test(rest)) rest = `${OPENING} ${rest}`.trim();
  // Sign-off: strip whatever the model used, then add the standard one.
  rest = rest.replace(/\n+(?:best|thanks|cheers|regards|kind regards|best regards|sincerely|warmly)[,!]?\s*\n+[\s\S]{0,80}$/i, "")
             .replace(/\n*\b(?:[A-Z][a-z]+\s*\n)?Pharos Support\s*$/i, "")
             .replace(/\s*\b(?:Alex)\s*$/,"")
             .trim()
             // a closing left on the last line, e.g. "...follow up. Best," or "Wishing you all the best,"
             .replace(/\s*\b(?:wishing you all the best|all the best|best regards|kind regards|warm regards|best|regards|thanks|thank you|cheers|sincerely|warmly|take care|all the best|wishing you all the best|with thanks)[^.!?\n]{0,25}[,!]?\s*$/i, "")
             .trim();
  return `${greeting ? greeting + "\n\n" : ""}${rest}\n\nBest,\n${AGENT}\nPharos Support`;
}

function polishTriage(raw, input = "") {
  const cleaned = String(raw).trim().replace(/^```(?:json)?\s*|\s*```$/g, "");
  let obj;
  try { obj = JSON.parse(cleaned); }
  catch {
    const m = cleaned.match(/\{[\s\S]*\}/);
    if (!m) return raw;
    try { obj = JSON.parse(m[0]); } catch { return raw; }
  }
  const from = String(input).match(/^From:\s*([A-Za-z][A-Za-z'-]*)/m);
  if (typeof obj.draft_reply === "string" && obj.category !== "spam") obj.draft_reply = fixDraft(obj.draft_reply, from ? from[1] : "");
  if (Array.isArray(obj.cited_articles)) obj.cited_articles = obj.cited_articles.map(s => String(s).split(">")[0].trim());
  return JSON.stringify(obj);
}

async function count(env, key) { const v = await env.LIMITS.get(key); return Number(v) || 0; }
async function bump(env, key, current) { await env.LIMITS.put(key, String(current + 1), { expirationTtl: 60 * 60 * 48 }); }
async function sha256(s) {
  const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(s));
  return [...new Uint8Array(buf)].map(b => b.toString(16).padStart(2, "0")).join("");
}
